#!/usr/bin/env python3
"""Write src/StaccData.h from tools/stacc.json and tools/stacc_onsets.npz (tools/staccato.py).

    python3 -I tools/make_stacc_header.py tools/stacc.json tools/stacc_onsets.npz src/StaccData.h

Per note and dynamic: the stroke's level (the four round robins' median) and the same from a quadratic
along the keys (Even Notes). Per kept take (two per note and dynamic): its onset as recorded, its level,
where its bow leaves, where the recording hands over and each harmonic's level and phase there, and the
same hand-off for the spiccato. For the tremolo (docs/TREMOLO.md), every take of a note and dynamic: where
its stroke starts (in its kept onset, or in a grain of its own), which way it was bowed, its level as a
tremolo stroke, and its fundamental's pitch and phase where the stroke starts.
"""
import json
import sys

import numpy as np

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from make_pizz_header import arr, ff  # noqa: E402


def main():
    js, npz, out = sys.argv[1:4]
    d = json.load(open(js))
    on = np.load(npz)
    onsets = on["onsets"].astype(np.float64) * float(on["scale"])
    grains = on["trem"].astype(np.float64) * float(on["scale"])
    notes, dyns, keep = d["notes"], d["dynamics"], d["keep"]
    nN, nD = len(notes), len(dyns)
    lv = np.array(d["levels"])
    x = np.array(notes, float)
    even = np.stack([np.polyval(np.polyfit(x, lv[:, j], 2), x) for j in range(nD)], axis=1)
    cells = {}
    for c in d["cells"]:
        cells.setdefault((c["midi"], c["dyn"]), []).append(c)
    takes = [cells[(m, dy)][r] for m in notes for dy in dyns for r in range(keep)]
    H = max(max(len(t["hand_db"]), len(t["sp_db"])) for t in takes)

    def db(v):
        v = list(v) + [-200.0] * (H - len(v))
        return [int(np.clip(round(a * 100), -12000, 3000)) for a in v]

    def ph(v):
        v = list(v) + [0.0] * (H - len(v))
        q = [int(round(a / np.pi * 128)) % 256 for a in v]      # as tools/make_header.py's
        return [a - 256 if a > 127 else a for a in q]

    scale = max(float(np.max(np.abs(onsets))), float(np.max(np.abs(grains)))) / 32767
    q = np.round(onsets / scale).astype(int)
    qg = np.round(grains / scale).astype(int)
    tr = d["trem"]
    per = max(len(c) for c in tr)

    def tcol(key, fill):
        return sum(([t[key] for t in c] + [fill] * (per - len(c)) for c in tr), [])
    n = len(takes)
    src = [
        "// Generated by tools/make_stacc_header.py from tools/stacc.json and tools/stacc_onsets.npz",
        "// (tools/staccato.py), measured from the Karoryfer x bigcat cello's staccatos (Karoryfer Samples and",
        "// bigcat instruments, cellist Kamila Borowiak; CC0). The onsets are excerpts of its recordings.",
        "// Do not edit by hand.",
        "#pragma once",
        "",
        "namespace stacc_data {",
        "",
        "constexpr int kOnsetRate = %d;" % d["onset_rate"],
        "constexpr int kNotes = %d, kDyns = %d, kKeep = %d;   // takes kept per note and dynamic" % (nN, nD, keep),
        "constexpr int kTakes = %d;      // (note × kDyns + dynamic) × kKeep + round robin" % n,
        "constexpr int kHarm = %d;" % H,
        "constexpr float kXf = %s, kSpXf = %s;   // the crossfades to the bank (s): staccato, spiccato" % (ff(d["xf"]), ff(d["sp_xf"])),
        "constexpr int kOnsetLen = %d;" % q.shape[1],
        "constexpr float kOnsetScale = %.6ef;" % scale,
        "",
        arr("noteMidi[kNotes]", "int", notes, str),
        "// the stroke's level (its harmonics' peak rms, dB): the takes' median; and from a quadratic along the keys",
        arr("level[kNotes][kDyns]", "float", lv.flatten(), ff, 4),
        arr("levelEven[kNotes][kDyns]", "float", even.flatten(), ff, 4),
        "// per take: its own level, where its bow leaves, where the recording hands over (s), the pitch there",
        arr("takeLevel[kTakes]", "float", [t["level"] for t in takes], ff, 8),
        arr("tOff[kTakes]", "float", [t["t_off"] for t in takes], ff, 8),
        arr("tHand[kTakes]", "float", [t["t_hand"] for t in takes], ff, 8),
        "// a stroke longer than the recording: how it fades from the hand-off to its bow-off (dB/s)",
        arr("fadeDbS[kTakes]", "float", [t["fade"] for t in takes], ff, 8),
        arr("handF0[kTakes]", "float", [t["hand_f0"] for t in takes], ff, 8),
        arr("handCount[kTakes]", "short", [len(t["hand_db"]) for t in takes], str),
        "// each harmonic's level (centi-dB, peak) and phase (π/128) at the hand-off's middle",
        arr("handDb[kTakes][kHarm]", "short", sum((db(t["hand_db"]) for t in takes), []), str, 24),
        arr("handPh[kTakes][kHarm]", "signed char", sum((ph(t["hand_ph"]) for t in takes), []), str, 32),
        "// each harmonic's decay after the bow leaves (deci-dB/s), the take's own",
        arr("relDbS[kTakes][kHarm]", "short", sum(([int(round(min(3000.0, v) * 10)) for v in t["rel"]] + [600] * (H - len(t["rel"])) for t in takes), []), str, 24),
        "// the spiccato: where its bow leaves (the recording hands over there), its level and pitch there,",
        "// and the harmonics there",
        arr("tSp[kTakes]", "float", [t["t_sp"] for t in takes], ff, 8),
        arr("spLevel[kTakes]", "float", [t["sp_level"] for t in takes], ff, 8),
        arr("spF0[kTakes]", "float", [t["sp_f0"] for t in takes], ff, 8),
        arr("spCount[kTakes]", "short", [len(t["sp_db"]) for t in takes], str),
        arr("spDb[kTakes][kHarm]", "short", sum((db(t["sp_db"]) for t in takes), []), str, 24),
        arr("spPh[kTakes][kHarm]", "signed char", sum((ph(t["sp_ph"]) for t in takes), []), str, 32),
        "// the tremolo: per note and dynamic (note × kDyns + dynamic), every take: its samples (>= 0: a kept",
        "// take's onset; < 0: grain -1 - src), where its stroke starts in them and how much follows (samples),",
        "// which way it was bowed (+1/-1), its level as a tremolo stroke (dB, as takeLevel), and its",
        "// fundamental's pitch (Hz) and phase (radians) where the stroke starts",
        "constexpr int kTremPer = %d, kTremGrains = %d, kTremLen = %d;" % (per, qg.shape[0], qg.shape[1]),
        arr("tremCount[kNotes * kDyns]", "signed char", [len(c) for c in tr], str, 16),
        arr("tremSrc[kNotes * kDyns][kTremPer]", "short", tcol("src", 0), str, 16),
        arr("tremStart[kNotes * kDyns][kTremPer]", "short", tcol("start", 0), str, 16),
        arr("tremAvail[kNotes * kDyns][kTremPer]", "short", tcol("avail", 0), str, 16),
        arr("tremDir[kNotes * kDyns][kTremPer]", "signed char", tcol("dir", 1), str, 16),
        arr("tremRef[kNotes * kDyns][kTremPer]", "float", tcol("ref", 0.0), ff, 8),
        arr("tremF0[kNotes * kDyns][kTremPer]", "float", tcol("f0", 100.0), ff, 8),
        arr("tremPh[kNotes * kDyns][kTremPer]", "float", tcol("ph", 0.0), ff, 8),
        "// the tremolo's grains of their own: kTremLen samples at kOnsetRate, times kOnsetScale",
        arr("tremGrain[kTremGrains][kTremLen]", "short", qg.flatten(), str, 24),
        "// the onsets: kOnsetLen samples at kOnsetRate, times kOnsetScale",
        arr("onset[kTakes][kOnsetLen]", "short", q.flatten(), str, 24),
        "}  // namespace stacc_data",
        "",
    ]
    with open(out, "w") as f:
        f.write("\n".join(src))
    print("wrote %s: %d takes, %d harmonics at most, onsets %.2f s (%.1f MB of samples); tremolo grains %d (%.1f MB)" % (
        out, n, H, q.shape[1] / d["onset_rate"], q.size * 2 / 1e6, qg.shape[0], qg.size * 2 / 1e6))


if __name__ == "__main__":
    main()
