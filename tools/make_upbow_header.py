#!/usr/bin/env python3
"""Write src/UpbowData.h from tools/upbow.json and tools/upbow_onsets.npz (tools/upbow.py).

    python3 -I tools/make_upbow_header.py tools/upbow.json tools/upbow_onsets.npz src/UpbowData.h

The up-bow onsets, quantised as src/CelloData.h's are: per take its samples, its pitch, level and each
harmonic's level (centi-dB) and phase (1/128 of pi) at the hand-off; per cell the take it plays (-1:
none steady, the down-bow onset plays for either bow).
"""
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_header import arr, ff  # noqa: E402


def main():
    js, npz, out = sys.argv[1:4]
    d = json.load(open(js))
    onsets = np.load(npz)["onsets"].astype(np.float64)
    notes, dyns = d["notes"], d["dynamics"]
    nN, nD, nT = len(notes), len(dyns), len(onsets)
    K = max(c["K"] for c in d["cells"] if c["take"] is not None)
    take = np.full((nN, nD), -1, int)
    hand_db = np.full((nT, K), -12000, int)
    hand_ph = np.zeros((nT, K), int)
    nk = np.zeros(nT, int)
    level = np.zeros(nT)
    hand_f0 = np.zeros(nT)
    for c in d["cells"]:
        i, j, t = notes.index(c["midi"]), dyns.index(c["dyn"]), c["index"]
        take[i, j] = t
        if t < 0:
            continue
        k = c["K"]
        nk[t] = k
        hand_db[t, :k] = np.clip(np.round(np.array(c["hand_db"]) * 100), -12000, 3000)
        hand_ph[t, :k] = np.round(np.array(c["hand_phase"]) / np.pi * 128).astype(int) % 256
        level[t] = c["level"]
        hand_f0[t] = c["hand_f0"]
    hand_ph = np.where(hand_ph > 127, hand_ph - 256, hand_ph)
    scale = float(np.max(np.abs(onsets))) / 32767
    q = np.round(onsets / scale).astype(int)
    src = [
        "// Generated by tools/make_upbow_header.py from tools/upbow.json and tools/upbow_onsets.npz",
        "// (tools/upbow.py), measured from the Karoryfer x bigcat cello's up-bow sustains (Karoryfer",
        "// Samples and bigcat instruments, cellist Kamila Borowiak; CC0). The onsets are excerpts of its",
        "// recordings. Do not edit by hand.",
        "#pragma once",
        "",
        "namespace upbow_data {",
        "",
        "constexpr int kOnsetRate = %d;" % d["onset_rate"],
        "constexpr int kNotes = %d, kDyns = %d;" % (nN, nD),
        "constexpr int kTakes = %d;      // up-bow takes stored" % nT,
        "constexpr int kHarm = %d;" % K,
        "constexpr int kOnsetLen = %d;" % onsets.shape[1],
        "constexpr float kOnsetScale = %.6ef;" % scale,
        "",
        arr("noteMidi[kNotes]", "int", notes, str),
        "// the take each cell's up bow starts from (-1: no steady up-bow take within a dynamic of it)",
        arr("take[kNotes][kDyns]", "int", take.flatten(), str, 4),
        "// per take: steady harmonic level (rms dBFS), the pitch at the hand-off (Hz)",
        arr("level[kTakes]", "float", level, ff, 8),
        arr("handF0[kTakes]", "float", hand_f0, ff, 8),
        "// harmonics measured, and each at the hand-off: level (centi-dB) and phase (1/128 of pi)",
        arr("handCount[kTakes]", "short", nk, str, 16),
        arr("handDb[kTakes][kHarm]", "short", hand_db.flatten(), str, 20),
        arr("handPh[kTakes][kHarm]", "signed char", hand_ph.flatten(), str, 32),
        "// the onsets: kOnsetLen samples at kOnsetRate, times kOnsetScale",
        arr("onset[kTakes][kOnsetLen]", "short", q.flatten(), str, 24),
        "}  // namespace upbow_data",
        "",
    ]
    with open(out, "w") as f:
        f.write("\n".join(src))
    print("wrote %s: %d takes for %d of %d cells" % (out, nT, int(np.sum(take >= 0)), nN * nD))


if __name__ == "__main__":
    main()
