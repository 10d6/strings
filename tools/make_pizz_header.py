#!/usr/bin/env python3
"""Write src/PizzData.h from tools/pizz.json and tools/pizz_onsets.npz (tools/pizz.py).

    python3 -I tools/make_pizz_header.py tools/pizz.json tools/pizz_onsets.npz src/PizzData.h

Per measured note (13, C2-C5) and round robin (4): the onset as recorded, the pitch it rings at, and
its harmonics as modes (one or two each: decay, frequency, level and phase at the hand-off). Per note:
its level (the round robins' median), the same from a smooth curve along the keyboard (Even Notes, as
the arco's: the plucked notes are as uneven, A2 and F#4 5-8 dB over their neighbours), and how fast it
falls over its first second (for notes between the measured ones, whose modes come from the nearest).
"""
import json
import sys

import numpy as np


def arr(name, ctype, values, fmt, per_line=16):
    flat = list(values)
    lines = []
    for i in range(0, len(flat), per_line):
        lines.append("  " + ", ".join(fmt(v) for v in flat[i:i + per_line]))
    return "constexpr %s %s = {\n%s};\n" % (ctype, name, ",\n".join(lines))


def ff(v):
    t = "%.6g" % v
    if not any(c in t for c in ".en"):
        t += ".0"
    return t + "f"


def main():
    js, npz, out = sys.argv[1:4]
    d = json.load(open(js))
    on = np.load(npz)
    onsets = on["onsets"].astype(np.float64) * float(on["scale"])
    notes, nR = d["notes"], d["rr"]
    nN = len(notes)
    cells = {(c["midi"], c["rr"]): c for c in d["cells"]}
    f0 = np.zeros((nN, nR))
    level = np.zeros((nN, nR))
    decay = np.zeros((nN, nR))
    start, count = [], []
    mk, mcents, mdf, mdecay, mdb, mph = [], [], [], [], [], []
    for i, m in enumerate(notes):
        for r in range(nR):
            c = cells[(m, r + 1)]
            f0[i, r] = c["f0"]
            level[i, r] = c["level"]
            decay[i, r] = c["decay"]
            start.append(len(mk))
            for k, modes in enumerate(c["harm"], start=1):
                for dec, df, lv, ph in modes:
                    mk.append(k)
                    mcents.append(c["dev"][k - 1])
                    mdf.append(df)
                    mdecay.append(dec)
                    mdb.append(lv)
                    mph.append(ph)
            count.append(len(mk) - start[-1])
    level_note = np.median(level, axis=1)
    level_even = np.polyval(np.polyfit(np.array(notes, float), level_note, 2), np.array(notes, float))
    decay_note = np.median(decay, axis=1)
    kmax = max(mk)
    q = np.round(onsets / (np.max(np.abs(onsets)) / 32767)).astype(int)
    scale = float(np.max(np.abs(onsets))) / 32767
    src = [
        "// Generated by tools/make_pizz_header.py from tools/pizz.json and tools/pizz_onsets.npz",
        "// (tools/pizz.py), measured from the Karoryfer x bigcat cello's pizzicato (Karoryfer Samples and",
        "// bigcat instruments, cellist Kamila Borowiak; CC0). The onsets are excerpts of its recordings.",
        "// Do not edit by hand.",
        "#pragma once",
        "",
        "namespace pizz_data {",
        "",
        "constexpr int kOnsetRate = %d;" % d["onset_rate"],
        "constexpr int kNotes = %d;      // measured notes, a minor third apart" % nN,
        "constexpr int kRR = %d;         // round robins per note" % nR,
        "constexpr float kTOn = %s, kXf = %s, kTC = %s;   // the onset's crossfade to the modes (s)" % (
            ff(d["t_on"]), ff(d["xf"]), ff(d["t_c"])),
        "constexpr int kOnsetLen = %d;" % q.shape[1],
        "constexpr float kOnsetScale = %.6ef;" % scale,
        "constexpr int kModes = %d;      // in all" % len(mk),
        "constexpr int kMaxModes = %d;   // in one note at most" % max(count),
        "constexpr int kMaxHarm = %d;    // the highest harmonic with a mode" % kmax,
        "",
        arr("noteMidi[kNotes]", "int", notes, str),
        "// the pitch each take rings at (Hz)",
        arr("f0[kNotes][kRR]", "float", f0.flatten(), ff, 4),
        "// how loud each take is heard (rms over its first 0.3 s, dBFS); per note the takes' median, and the same",
        "// from a quadratic along the keyboard (Even Notes)",
        arr("level[kNotes][kRR]", "float", level.flatten(), ff, 4),
        arr("levelNote[kNotes]", "float", level_note, ff, 8),
        arr("levelEven[kNotes]", "float", level_even, ff, 8),
        "// how fast each note falls over its first second (dB/s, the takes' median)",
        arr("decayNote[kNotes]", "float", decay_note, ff, 8),
        "// each take's modes: where they start in the tables below and how many",
        arr("modeStart[kNotes * kRR]", "int", start, str),
        arr("modeCount[kNotes * kRR]", "short", count, str),
        "// per mode: its harmonic (1-based), where the harmonic is (cents from k·f0), its own offset",
        "// (Hz), its decay (dB/s), its peak level (dBFS) and phase (rad) at kTC",
        arr("modeK[kModes]", "short", mk, str, 24),
        arr("modeCents[kModes]", "float", mcents, ff, 12),
        arr("modeDf[kModes]", "float", mdf, ff, 12),
        arr("modeDecay[kModes]", "float", mdecay, ff, 12),
        arr("modeDb[kModes]", "float", mdb, ff, 12),
        arr("modePh[kModes]", "float", mph, ff, 12),
        "// the onsets, per note and round robin: kOnsetLen samples at kOnsetRate, times kOnsetScale",
        arr("onset[kNotes * kRR][kOnsetLen]", "short", q.flatten(), str, 24),
        "}  // namespace pizz_data",
        "",
    ]
    with open(out, "w") as f:
        f.write("\n".join(src))
    print("wrote %s: %d takes, %d modes (at most %d in a take, harmonics to %d); levels %s; decays %s dB/s" % (
        out, nN * nR, len(mk), max(count), kmax, " ".join("%.1f" % v for v in level_note),
        " ".join("%.0f" % v for v in decay_note)))


if __name__ == "__main__":
    main()
