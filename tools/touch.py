#!/usr/bin/env python3
"""Measure natural harmonics from bigcat's four harmonic slides: src/TouchData.h.

    python3 -I tools/touch.py <bigcat checkout> src/TouchData.h

Each slide (noises/{c1,g1,d2,a2}_harmonics.wav) bows one open string (C2, G2, D3, A3; bigcat names an
octave low) for its first half second, then a finger brushes along it, crossing its harmonic nodes. At
a node 1/n along, the touched string keeps only its harmonics that are multiples of n: the note sounds
n times the open string's pitch, with the string's own harmonics n, 2n, 3n, ... On the C and G strings
the frequencies stay on the open string's harmonics throughout; on D and A the finger also partly stops
the string between nodes (partials sweep in arcs), so only clear node frames are used.

Frames (0.12 s, every 20 ms) where one node holds: the first three multiples of n stand 18 dB over the
mean of the other harmonics up to 5n (n = 2-6; 0.1-1.8 s of frames per string and node). Per node and
string, the kept harmonics' shape (each multiple m's level against the first) against what the open
string's own bowed spectrum (its first 0.5 s) has at the same harmonics: what the finger takes. Pooled
by m over every node and string (the median: one string's node scatters by ±10 dB), made monotonic,
and continued past the last measured m at the last octave's slope. And the level: the kept harmonics'
power against the open string's, the median over nodes and strings.

Measured: the finger leaves the first few kept harmonics about as the bowed string has them and takes
progressively more (about 6 dB by the 4th, 10 by the 6th): a purer, flute-like tone; a harmonic is
about 6 dB under the open string bowed alike (−3 to −9 by node; the A string's open start was loud
against its harmonics, −22, and pulls no median).
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C  # noqa: E402

KM = 40
TH = 18.0
NODES = range(2, 7)
SLIDES = [("c1", 36), ("g1", 43), ("d2", 50), ("a2", 57)]
MOUT = 64


def frames(x, sr, fo):
    W, hop = int(0.12 * sr), int(0.02 * sr)
    w = np.hanning(W)
    nfft = 1 << 15
    fr = np.fft.rfftfreq(nfft, 1 / sr)
    sel = [(fr > k * fo * 0.985) & (fr < k * fo * 1.015) for k in range(1, KM + 1)]
    for i in range(0, len(x) - W, hop):
        S = np.abs(np.fft.rfft(x[i:i + W] * w, nfft)) ** 2
        yield i / sr, np.array([10 * np.log10(S[s].max() + 1e-20) for s in sel])


def main():
    root, out = sys.argv[1:3]
    per_m = {}
    gains = []
    for name, opn in SLIDES:
        x, sr = C.load(os.path.join(root, "Samples", "noises", name + "_harmonics.wav"))
        _, f0s, _ = C.track_f0(x[int(0.05 * sr):int(0.5 * sr)], sr, C.mtof(opn))
        fo = float(np.nanmedian(f0s))
        opens, nodes = [], {n: [] for n in NODES}
        for t, lv in frames(x, sr, fo):
            if 0.05 < t < 0.5:
                opens.append(lv)
                continue
            best = None
            for n in range(2, 8):
                mult = [lv[k - 1] for k in range(n, KM + 1, n)][:3]
                non = [lv[k - 1] for k in range(1, min(KM, 5 * n) + 1) if k % n]
                sc = np.mean(mult) - np.mean(non)
                if best is None or sc > best[1]:
                    best = (n, sc)
            if best[1] > TH and best[0] in nodes:
                nodes[best[0]].append(lv)
        O = np.median(opens, axis=0)
        o_tot = 10 * np.log10(np.sum(10 ** (O / 10)))
        for n, fl in nodes.items():
            if len(fl) < 3:
                continue
            L = np.median(fl, axis=0)
            for m in range(1, KM // n + 1):
                per_m.setdefault(m, []).append((L[n * m - 1] - L[n - 1]) - (O[n * m - 1] - O[n - 1]))
            gains.append(10 * np.log10(np.sum(10 ** (L[n - 1::n] / 10))) - o_tot)
    ms = sorted(m for m in per_m if len(per_m[m]) >= 4)
    take = np.array([np.median(per_m[m]) for m in ms])
    take = np.minimum.accumulate(np.minimum(take, 0.0))       # the finger only takes, more higher up
    slope = (take[-1] - take[ms.index(max(1, ms[-1] // 2))]) if len(ms) > 2 else 0.0   # dB per octave
    curve = []
    for m in range(1, MOUT + 1):
        if m <= ms[-1]:
            curve.append(float(np.interp(m, ms, take)))
        else:
            curve.append(float(take[-1] + slope * np.log2(m / ms[-1])))
    level = float(np.median(gains))
    src = [
        "// Generated by tools/touch.py from the Karoryfer x bigcat cello's harmonic slides (CC0). Do not edit.",
        "#pragma once",
        "",
        "namespace touch_data {",
        "",
        "// A natural harmonic against the open string bowed alike: its level (dB, the median over nodes 2-6",
        "// and the four strings), and what the finger takes from each kept harmonic m (the string's n·m-th)",
        "// beyond what the bowed string's own spectrum has there (dB; m = 1 is the sounding pitch).",
        "constexpr float kLevelDb = %.2ff;" % level,
        "constexpr int kM = %d;" % MOUT,
        "constexpr float takeDb[kM] = {",
        "  " + ", ".join("%.2ff" % v for v in curve),
        "};",
        "}  // namespace touch_data",
        "",
    ]
    with open(out, "w") as f:
        f.write("\n".join(src))
    print("level %+.1f dB (%d nodes × strings: %s); the finger takes (m = 1-12): %s; %d m measured, then %+.1f dB/oct" % (
        level, len(gains), " ".join("%+.0f" % g for g in gains), " ".join("%+.1f" % v for v in curve[:12]), ms[-1], slope))


if __name__ == "__main__":
    main()
